def _get_init_file_details(
    engine: str,
    project_name: str,
) -> tuple[str, str]:
    if engine == "postgresql":
        return (
            "init.sql",
            _postgresql_init_content(
                project_name,
            ),
        )

    if engine == "mysql":
        return (
            "init.sql",
            _mysql_init_content(
                project_name,
            ),
        )

    if engine == "mongodb":
        return (
            "init.js",
            _mongodb_init_content(
                project_name,
            ),
        )

    if engine == "sqlite":
        return (
            "init.sql",
            _sqlite_init_content(
                project_name,
            ),
        )

    raise ValueError(
        f"Unsupported database engine: {engine}"
    )


def generate_database_files(
    project_dir: Path,
    model: ArchitectureModel,
) -> dict[str, Any]:
    """
    Generate a simple initialization file for one supported database.

    Supported database engines:

    - PostgreSQL
    - MySQL
    - MongoDB
    - SQLite
    """

    component, engine = find_supported_database(
        model,
    )

    if component is None or engine is None:
        return {
            "database_engine": None,
            "generated_database_component_id": None,
            "generated_database_files": [],
            "skipped_database_components": (
                get_skipped_database_components(
                    model,
                )
            ),
        }

    database_dir = (
        Path(project_dir)
        / "database"
    )

    database_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    filename, content = (
        _get_init_file_details(
            engine,
            model.name,
        )
    )

    init_file = (
        database_dir
        / filename
    )

    init_file.write_text(
        content,
        encoding="utf-8",
    )

    return {
        "database_engine": engine,
        "generated_database_component_id": component.id,
        "generated_database_files": [
            str(
                init_file.relative_to(
                    project_dir,
                )
            )
        ],
        "skipped_database_components": (
            get_skipped_database_components(
                model,
                generated_component_id=component.id,
            )
        ),
    }