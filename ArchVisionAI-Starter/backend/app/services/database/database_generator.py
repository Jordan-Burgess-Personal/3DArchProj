def _normalize_text(value: object) -> str:
    return str(value or "").strip().lower()


def _component_search_text(
    component: Component,
) -> str:
    values = [
        component.id,
        component.name,
        component.type,
        component.technology,
        component.description,
    ]

    metadata = getattr(
        component,
        "metadata",
        None,
    )

    if isinstance(metadata, dict):
        values.extend(
            [
                metadata.get("technology"),
                metadata.get("database"),
                metadata.get("provider"),
                metadata.get("engine"),
                metadata.get("runtime"),
            ]
        )

    return " ".join(
        str(value)
        for value in values
        if value
    ).lower()


def is_database_component(
    component: Component,
) -> bool:
    if _normalize_text(component.type) == "database":
        return True

    search_text = _component_search_text(
        component,
    )

    return any(
        technology in search_text
        for technology in SUPPORTED_DATABASES
    )


def detect_database_engine(
    component: Component,
) -> str | None:
    search_text = _component_search_text(
        component,
    )

    detection_order = [
        ("postgresql", "postgresql"),
        ("postgres", "postgresql"),
        ("mongodb", "mongodb"),
        ("mongo", "mongodb"),
        ("mysql", "mysql"),
        ("sqlite", "sqlite"),
    ]

    for token, engine in detection_order:
        if token in search_text:
            return engine

    return None


def find_supported_database(
    model: ArchitectureModel,
) -> tuple[Component | None, str | None]:
    """
    Return the first supported database component.

    SCRUM-67 generates configuration for one database service.
    Additional database components remain in architecture.json but are
    reported as skipped.
    """

    for component in model.components:
        if not is_database_component(
            component,
        ):
            continue

        engine = detect_database_engine(
            component,
        )

        if engine:
            return component, engine

    return None, None


def get_skipped_database_components(
    model: ArchitectureModel,
    generated_component_id: str | None = None,
) -> list[str]:
    skipped: list[str] = []

    for component in model.components:
        if not is_database_component(
            component,
        ):
            continue

        if (
            generated_component_id is not None
            and component.id == generated_component_id
        ):
            continue

        skipped.append(component.name)

    return skipped


def _postgresql_init_content(
    project_name: str,
) -> str:
    return f"""-- Generated by ArchVision AI
-- Project: {project_name}
-- Database: PostgreSQL

CREATE TABLE IF NOT EXISTS app_health (
    id SERIAL PRIMARY KEY,
    status VARCHAR(50) NOT NULL DEFAULT 'healthy',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO app_health (status)
VALUES ('healthy');
"""


